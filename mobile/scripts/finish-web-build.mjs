#!/usr/bin/env node
/**
 * Adds to the exported web build what Expo's HTML template leaves out.
 *
 * The beta ships as a web app rather than through the stores: no app review —
 * firearms content policies are a real rejection risk — and a club official can
 * send a link instead of an invitation to install something.
 *
 * A `+html.tsx` would be the tidy way to do this, but that is only used when
 * `web.output` is "static". This project exports "single", because the public
 * pages a crawler needs are already served as real HTML by the public-pages
 * edge function, and one bundle is simpler to host. So the head is patched
 * here instead, as an explicit step rather than a silent one.
 *
 *   node scripts/finish-web-build.mjs [dist]
 */

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MOBILE = resolve(fileURLToPath(new URL('..', import.meta.url)));
const DIST = resolve(process.argv[2] ?? join(MOBILE, 'dist'));
const INDEX = join(DIST, 'index.html');

if (!existsSync(INDEX)) {
  console.error(`No build at ${INDEX}. Run "npm run build:web" first.`);
  process.exit(1);
}

const HEAD = `
    <script>
      // Registered from the shell rather than from React, so a boot that fails
      // still leaves a worker able to serve the last good build.
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('/sw.js').catch(function () {});
        });
      }
    </script>
    <meta name="description" content="An online league for sport shooters on electronic targets. Shoot at your own club, report the score with a photo, and neither result is visible until both have submitted." />
    <link rel="manifest" href="/manifest.webmanifest" />
    <link rel="apple-touch-icon" href="/icon-512.png" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="WSL" />
    <meta name="theme-color" media="(prefers-color-scheme: light)" content="#F7F8FB" />
    <meta name="theme-color" media="(prefers-color-scheme: dark)" content="#0B0D13" />
    <style>
      /* Painted before the bundle boots. Without it a phone flashes white,
         which on a dark device at a dim range is a slap in the face. */
      html, body { background-color: #F7F8FB; }
      @media (prefers-color-scheme: dark) {
        html, body { background-color: #0B0D13; }
      }
    </style>
`;

let html = readFileSync(INDEX, 'utf8');

if (html.includes('manifest.webmanifest')) {
  console.log('already finished, nothing to do');
  process.exit(0);
}

// viewport-fit=cover is what lets the safe-area insets reach the tab bar once
// the app is installed to a home screen and runs without browser chrome.
html = html.replace(
  'content="width=device-width, initial-scale=1, shrink-to-fit=no"',
  'content="width=device-width, initial-scale=1, shrink-to-fit=no, viewport-fit=cover"',
);

html = html.replace('</head>', `${HEAD}  </head>`);

writeFileSync(INDEX, html);

// ------------------------------------------------------- service worker ----

/**
 * Why this is generated rather than committed: the bundle filename carries a
 * content hash that changes every build, so a hand-written worker would either
 * have to guess it or cache nothing.
 *
 * What it buys is the one thing the offline story was missing. The outbox keeps
 * a report safe without reception and the query cache keeps the open matches
 * readable — but neither helps if the app will not start, and a web app with no
 * worker will not start without a network. A range is a concrete box in a
 * basement; opening the app there is the normal case, not the edge case.
 */
function filesUnder(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? filesUnder(full) : [full];
  });
}

const precache = filesUnder(DIST)
  .map((file) => '/' + relative(DIST, file).split(/[\\/]/).join('/'))
  // metadata.json is build bookkeeping and _redirects is a host's routing
  // config; neither is ever fetched by the app.
  .filter((path) => !['/metadata.json', '/_redirects', '/sw.js'].includes(path));

// The cache name has to change whenever anything in it does, or a phone keeps
// serving last week's build for as long as the worker lives.
const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);

const SW = `/* Generated by scripts/finish-web-build.mjs — do not edit. */
const CACHE = 'wsl-${version}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Only this origin. Everything Supabase — the API, the storage, the auth
  // endpoints — must be allowed to fail, because the app's own offline paths
  // are built on the failure. A worker that answered them from a cache would
  // show a stale score, and one of those is the opponent's.
  if (url.origin !== self.location.origin) return;

  // A navigation is the whole point: serve the shell from the cache when the
  // network is not there, which is what makes a cold start in a basement work.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => caches.match('/index.html').then((r) => r || Response.error())),
    );
    return;
  }

  // Everything else here is content-hashed, so the cache is authoritative.
  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request)),
  );
});
`;

writeFileSync(join(DIST, 'sw.js'), SW);

console.log(
  `web build finished: manifest, theme colour, safe-area viewport, ` +
    `service worker (${precache.length} files, ${version})`,
);
